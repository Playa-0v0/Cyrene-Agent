#!/usr/bin/env python3
"""Windows-first command line workflow for producing polished PDF reports."""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
SKILLS_DIR = SCRIPT_DIR.parents[1]
REQUIRED_PACKAGES = ("reportlab", "pypdf")
OPTIONAL_PACKAGES = ("pypdfium2", "matplotlib")


def dependency_report() -> dict[str, Any]:
    required = {name: importlib.util.find_spec(name) is not None for name in REQUIRED_PACKAGES}
    optional = {name: importlib.util.find_spec(name) is not None for name in OPTIONAL_PACKAGES}
    return {
        "status": "ok" if all(required.values()) else "error",
        "required": required,
        "optional": optional,
        "python": sys.version.split()[0],
    }


def require_dependencies() -> None:
    report = dependency_report()
    missing = [name for name, present in report["required"].items() if not present]
    if missing:
        raise RuntimeError(
            "Missing Python packages: " + ", ".join(missing)
            + ". Install them with: python -m pip install " + " ".join(missing)
        )


def default_content(title: str) -> list[dict[str, Any]]:
    return [
        {"type": "h1", "text": title},
        {"type": "body", "text": "This document was generated by the Windows-native PDF workflow."},
        {"type": "h2", "text": "Summary"},
        {"type": "bullet", "text": "Cover and body share one token set."},
        {"type": "bullet", "text": "All rendering runs through local Python libraries."},
    ]


def load_content(path: str | None, title: str) -> list[dict[str, Any]]:
    if not path:
        return default_content(title)
    with Path(path).open(encoding="utf-8") as handle:
        content = json.load(handle)
    if not isinstance(content, list):
        raise ValueError("Content JSON must be a list of blocks")
    return content


def apply_windows_fonts(tokens: dict[str, Any]) -> None:
    from pdf_cover import resolve_font_paths

    cjk_path = resolve_font_paths().get("cjk")
    if not cjk_path:
        return
    tokens["font_paths"] = {"CyrenePdfCjk": cjk_path}
    tokens["font_display_rl"] = "CyrenePdfCjk"
    tokens["font_body_rl"] = "CyrenePdfCjk"


def apply_theme(tokens: dict[str, Any], theme_id: str | None) -> None:
    if not theme_id:
        return
    theme_path = SKILLS_DIR / "office-design" / "assets" / "themes" / f"{theme_id}.json"
    if not theme_path.exists():
        raise ValueError(f"Unknown theme: {theme_id}")
    with theme_path.open(encoding="utf-8") as handle:
        theme = json.load(handle)
    colors = theme["colors"]
    tokens.update({
        "theme_id": theme["id"],
        "accent": colors["accent"],
        "accent_lt": colors["surface"],
        "dark": colors["foreground"],
        "muted": colors["muted"],
        "page_bg": colors["background"],
        "cover_bg": colors["primary"],
        "cover_fg": colors["background"],
    })


def build_pdf(args: argparse.Namespace, content_blocks: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    require_dependencies()
    from merge import merge
    from palette import build_tokens
    from pdf_cover import render_cover
    from render_body import build as build_body

    output_path = Path(args.out).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    content = content_blocks if content_blocks is not None else load_content(args.content, args.title)
    tokens = build_tokens(
        title=args.title,
        doc_type=args.type,
        author=args.author,
        date=args.date,
        accent_override=args.accent or "",
        cover_bg_override=args.cover_bg or "",
    )
    tokens["subtitle"] = args.subtitle
    tokens["abstract"] = args.abstract
    tokens["cover_image"] = args.cover_image
    apply_theme(tokens, args.theme)
    apply_windows_fonts(tokens)

    with tempfile.TemporaryDirectory(prefix=".cyrene-pdf-", dir=output_path.parent) as temp_dir:
        temp_path = Path(temp_dir)
        cover_path = temp_path / "cover.pdf"
        body_path = temp_path / "body.pdf"
        combined_path = temp_path / "combined.pdf"
        render_cover(tokens, cover_path)
        build_body(tokens, content, str(body_path))
        report = merge(str(cover_path), str(body_path), str(combined_path), args.title)
        if report["status"] != "ok":
            raise RuntimeError(report["error"])
        os.replace(combined_path, output_path)

    report["out"] = str(output_path)
    report["theme"] = tokens.get("theme_id")
    report["renderer"] = "python"
    return report


def reformat(args: argparse.Namespace) -> dict[str, Any]:
    require_dependencies()
    from reformat_parse import parse_file

    content, warnings = parse_file(args.input)
    if not content:
        raise ValueError("No content blocks extracted from input")
    output = build_pdf(args, content)
    output["warnings"] = warnings
    return output


def preview(args: argparse.Namespace) -> dict[str, Any]:
    require_dependencies()
    from render_preview import render_pages
    return render_pages(Path(args.input), Path(args.out_dir), args.dpi)


def fill(args: argparse.Namespace) -> int:
    script = SCRIPT_DIR / ("fill_inspect.py" if args.inspect else "fill_write.py")
    command = [sys.executable, str(script), "--input", args.input]
    if args.inspect:
        return subprocess.run(command, check=False).returncode
    command.extend(["--out", args.out])
    if args.values:
        command.extend(["--values", args.values])
    if args.data:
        command.extend(["--data", args.data])
    return subprocess.run(command, check=False).returncode


def demo(args: argparse.Namespace) -> dict[str, Any]:
    args.title = "Windows Native PDF Demo"
    args.type = "report"
    args.author = "Cyrene"
    args.date = "2026"
    args.subtitle = "A browser-free rendering workflow"
    args.abstract = "Shared tokens keep the cover and document body visually consistent."
    args.content = None
    return build_pdf(args)


def common_options(parser: argparse.ArgumentParser, *, include_input: bool = False) -> None:
    if include_input:
        parser.add_argument("--input", required=True)
    parser.add_argument("--title", required=not include_input)
    parser.add_argument("--type", default="report")
    parser.add_argument("--author", default="")
    parser.add_argument("--date", default="")
    parser.add_argument("--subtitle", default="")
    parser.add_argument("--abstract", default="")
    parser.add_argument("--accent")
    parser.add_argument("--cover-bg")
    parser.add_argument("--cover-image")
    parser.add_argument("--theme")
    parser.add_argument("--out", required=True)


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__)
    commands = root.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="check required local Python packages")

    run = commands.add_parser("run", help="create a PDF from JSON content")
    common_options(run)
    run.add_argument("--content")

    reform = commands.add_parser("reformat", help="reformat Markdown, text, PDF, or JSON")
    common_options(reform, include_input=True)

    prev = commands.add_parser("preview", help="render PDF pages to PNG files")
    prev.add_argument("--input", required=True)
    prev.add_argument("--out-dir", required=True)
    prev.add_argument("--dpi", type=int, default=144)

    form = commands.add_parser("fill", help="inspect or fill form fields")
    form.add_argument("--input", required=True)
    form.add_argument("--out", default="filled.pdf")
    form.add_argument("--inspect", action="store_true")
    form.add_argument("--values")
    form.add_argument("--data")

    demo_parser = commands.add_parser("demo", help="create a sample PDF")
    demo_parser.add_argument("--out", required=True)
    demo_parser.add_argument("--theme")
    demo_parser.set_defaults(accent=None, cover_bg=None, cover_image=None)
    return root


def main() -> int:
    args = parser().parse_args()
    try:
        if args.command == "check":
            report = dependency_report()
            print(json.dumps(report, ensure_ascii=False))
            return 0 if report["status"] == "ok" else 2
        if args.command == "run":
            result = build_pdf(args)
        elif args.command == "reformat":
            result = reformat(args)
        elif args.command == "preview":
            result = preview(args)
        elif args.command == "fill":
            return fill(args)
        else:
            result = demo(args)
        print(json.dumps(result, ensure_ascii=False))
        return 0
    except Exception as error:
        print(json.dumps({"status": "error", "error": str(error)}, ensure_ascii=False), file=sys.stderr)
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
